static const u8 *glyph(char c) {
    int i;
    if (c >= 'a' && c <= 'z') c -= 32;
    for (i = 0; chars[i]; i++)
        if (chars[i] == c) return glyphs[i];
    return glyphs[37]; /* '?' */
}

int font_width(const char *s, int scale) {
    int n = 0;
    while (s[n]) n++;
    return n * 6 * scale;
}

int font_text(int x, int y, const char *s, int scale, u16 fg, u16 bg) {
    int c, r;
    for (; *s; s++) {
        const u8 *g = glyph(*s);
        lcd_fill(x, y, 6 * scale, 8 * scale, bg);
        for (c = 0; c < 5; c++)
            for (r = 0; r < 7; r++)
                if (g[c] >> r & 1) lcd_fill(x + c * scale, y + r * scale, scale, scale, fg);
        x += 6 * scale;
    }
    return x;
}

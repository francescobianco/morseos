/*
 * MorseOS framework: apps, menus, input, screen.
 *
 * An app is a mos_app_t. The bundle (tools/bundle.py) lists the selected apps in
 * mos_entries[] with the menu they belong to; the menus are built from that table:
 *   main menu  = apps with menu "MENU", then one box per other menu name (STRUMENTI,
 *                GIOCHI, ...) that has at least one app, then TORNA
 *   submenu    = its apps, then INDIETRO
 * The home app (flag MOS_F_HOME, the watch face) is shown on wake-up and on timeouts.
 */
#ifndef MOS_H
#define MOS_H

#include "tl_common.h"
#include "bundle.h"

/* key events delivered to app->key() */
enum {
    MOS_KEY_SHORT,  /* released before the long threshold */
    MOS_KEY_HOLD,   /* long threshold reached, key still down (only with MOS_F_LONG) */
    MOS_KEY_LONG,   /* released after the long threshold (only with MOS_F_LONG) */
};

#define MOS_F_MORSE     0x01 /* the touch key feeds the Morse decoder while the app is shown */
#define MOS_F_LONG      0x02 /* short/long touch: buzz + MOS_KEY_HOLD at 600 ms */
#define MOS_F_HOLD_EXIT 0x04 /* holding the key 3 s goes back to the menu */
#define MOS_F_HOME      0x08 /* the home screen (watch face) */

typedef struct mos_app {
    const char *name;
    u8 flags;
    u8 timeout_s;                     /* screen off after this idle time, 0 = 30 s */
    void (*enter)(void);              /* the app becomes active (before draw) */
    void (*draw)(void);               /* full redraw */
    void (*tick)(void);               /* every main-loop pass while active and the screen is on */
    void (*key)(int event);           /* touch key, see MOS_KEY_* */
    void (*letter)(char c);           /* Morse letter (MOS_F_MORSE) */
    void (*pattern)(const char *pat); /* Morse elements of the current letter */
    void (*word)(const char *word);   /* Morse letters so far */
    void (*access)(void);             /* Morse access word typed */
} mos_app_t;

typedef struct {
    const char *menu;  /* "MENU", a submenu name, or "" for apps opened by other means */
    const char *label;
    const mos_app_t *app;
} mos_entry_t;

extern const mos_entry_t mos_entries[];  /* generated by tools/bundle.py */
extern const int mos_entry_count;

/* system */
void mos_init(void (*buzz)(int ms), void (*notify)(const u8 *pkt, int len));
void mos_poll(int touched);
void mos_set_connected(int on);
int  mos_connected(void);
void mos_set_peer(const char *name);  /* remote device name (GAP 0x2A00), 0 = unknown */
const char *mos_peer(void);           /* its first 3 letters, upper case, "" = unknown */
void mos_set_rssi(int dbm);
int  mos_rssi(void);                  /* dBm of the link */
int  mos_signal_bars(void);           /* 0..4 */
void mos_buzz(int ms);
void mos_notify(const u8 *pkt, int len);
u32  mos_press_ms(void);
u32  mos_ms_since(u32 tick);

/* navigation */
void mos_open(const mos_app_t *app);
void mos_home(void);
void mos_menu(const char *name);  /* "MENU" or a submenu name */
void mos_back(void);              /* the menu the active app was opened from */
int  mos_active(const mos_app_t *app);

/* screen: drawing works with the screen off too (the panel keeps the image, only the
 * backlight is off), so apps can prepare their screen in the dark and appear at once */
int  mos_screen_on(void);
void mos_wake(void);
void mos_redraw(void);
void mos_emergency_warning(int stage, int taps);  /* 0 off, 1 held, 2 counting taps */

/* drawing helpers */
char *mos_num(char *p, u32 v, int width);  /* decimal, zero-padded to width; returns the end */
void mos_center_text(int y, const char *s, int scale, u16 fg);
void mos_pattern_at(int y, const char *pat, u16 color, int centered);  /* dots and dashes */

#endif
